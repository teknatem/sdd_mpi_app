//! Механизм Процессов (ADR-0011).
//!
//! Термины — в `CONTEXT.md`, раздел «Механизм процессов»:
//!
//! - **Процесс** (`pr0001`) — граф Этапов, версия, триггер.
//! - **Этап** (`st0001`) — единица исполнения: mjs-модуль с именованными
//!   выходами, вызывающий Действия.
//! - **Действие** — операция ядра с побочным эффектом на Rust, закрытая
//!   `capability` `action:<name>`.
//! - **Экземпляр процесса** — долговечное состояние одного прогона по графу.
//!
//! Слои построены снизу вверх, и порядок не случаен: пока эффект не
//! идемпотентен и не журналируется, а исход Этапа не отделён от дефекта, всё,
//! что строится сверху, небезопасно по определению.
//!
//! - `actions` + `effect_log` — Действия и журнал эффектов;
//! - `stages` — исполнение Этапа и статическая проверка его определения;
//! - `events` — каталог доменных фактов и их журнал;
//! - `graph` — статическая проверка графа Процесса;
//! - `repository` + `definitions` — хранение определений с версиями и гейт
//!   активации;
//! - `instances` + `steps` + `worker` — долговечное состояние прогона, журнал
//!   его шагов и то, что его двигает.
//!
//! - `pilot` — определения `pr0001` «Закрытие дня WB», засеваемые черновиками.
//!
//! Чего ещё нет: точки публикации `import.day.completed` (её ставит тот, кто
//! знает, каким импортом день считается собранным) и экранов механизма. План —
//! `docs/plans/2026-08-22-processes-mechanism.md`.

