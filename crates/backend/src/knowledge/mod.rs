//! Инвентаризация знаний: сколько знания в системе есть и сколько из него
//! достижимо.
//!
//! Метод, реестр поверхностей и оси классификации заданы нормативным документом
//! `memory-bank/architecture/knowledge-inventory.md`. Здесь он исполняется.
//!
//! **Зачем отдельный механизм.** `/api/kb/stats` считает markdown-статьи — это
//! примерно пятая часть того, откуда чат берёт знание. Реестр сущностей,
//! источники данных, план счетов, quality-проверки, плагины, Процессы,
//! Действия, навыки и каталог инструментов не посчитаны нигде. Пока их нет в
//! счёте, невозможно ни оценить бюджет контекста, ни заметить, что до
//! поверхности не дотягивается ни один инструмент.
//!
//! **Ключевое различение, без которого подсчёт бессмыслен:** «есть» и
//! «доступно» — разные числа, и разница между ними и есть главный результат.
//!
//! Раскладка слоя повторяет `system/metrics/`, и не случайно: задача та же —
//! снять снимок, положить рядом с предыдущим и показать движение.
//!
//! | Файл | Роль |
//! |---|---|
//! | `catalog.rs` | реестр поверхностей — что вообще бывает |
//! | `tool_map.rs` | что отдаёт каждый инструмент чата — из этого считается достижимость |
//! | `collector.rs` | обход реестров и сбор единиц |
//! | `summary.rs` | сводка §6: числа и поимённые списки |
//! | `repository.rs` | снимки в БД |
//! | `service.rs` | сборка ответа страницы и инструмента |

