//! Метрики проекта: снимок состояния экземпляра и кодовой базы на каждый старт.
//!
//! Подсистема отвечает на вопрос «куда движется приложение», а не «что в нём
//! сейчас». Отсюда две особенности.
//!
//! **Снимок, а не запрос.** Одно значение без предыдущего ничего не говорит,
//! поэтому цифры фиксируются при каждом запуске в `sys_metric_snapshot` и живут
//! дольше процесса. Страница показывает последний снимок и дельту к предыдущему.
//!
//! **Два семейства с разной природой.** Рантайм-метрики (БД, качество данных,
//! аудит доступа) собираются здесь из уже существующих дешёвых источников.
//! Метрики кода посчитать в рантайме нельзя — исходников рядом с боевым
//! бинарём нет, — поэтому они вшиты в него на сборке (см. `codebase.rs`).
//!
//! Ни один источник не сканирует данные: подробности — в `collector.rs`.

