-- Стоимость вызова инструмента в токенах: сколько контекста реально доставлено
-- модели этим вызовом.
--
-- Зачем: в журнале была только длительность (`ms`), то есть «сколько ждали», но
-- не «сколько заплатили». Главный расходуемый ресурс чата — окно контекста, и до
-- этой колонки его тратили вслепую: нельзя было ни назвать самый дорогой
-- инструмент, ни увидеть, что статья на 4 500 токенов доставлена и ни разу не
-- процитирована.
--
-- Считается по строке результата, УХОДЯЩЕЙ в модель (`ChatMessage::tool_result`),
-- а не по `output_json`: последний — отобранный whitelist'ом снимок для UI, он
-- заметно короче доставленного и мерить по нему значило бы занижать.
--
-- Оценщик — `estimate_tokens` (shared/llm/knowledge_base.rs), тот же, что даёт
-- `token_cost` статьям базы знаний. Своего заводить нельзя: два оценщика дадут
-- два несравнимых бюджета.
--
-- 0 у строк-гардов и у записей до этой миграции: гард ничего в модель не
-- отправляет, а исторические вызовы измерить задним числом нечем.

ALTER TABLE sys_tool_trace ADD COLUMN tokens INTEGER NOT NULL DEFAULT 0;

CREATE INDEX IF NOT EXISTS idx_sys_tool_trace_tokens
    ON sys_tool_trace (tokens DESC)
    WHERE tokens > 0;
