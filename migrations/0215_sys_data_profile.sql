-- Профиль данных: сколько строк в таблице, за какой период они есть и насколько
-- заполнены ссылки. Одна строка = одна таблица каталога метаданных.
--
-- Зачем отдельная таблица, а не расчёт на лету: профиль отдаётся в
-- `get_entity_schema`, то есть внутри цикла чата, где лишние секунды дороже
-- свежести. Пересчёт дешёвый (COUNT/MIN/MAX идут по индексам), но делается
-- по требованию и при старте, а не на каждый вопрос.
--
-- Чего здесь принципиально нет: самих данных. Это метрики о таблице, поэтому
-- строка живёт ровно до следующего пересчёта и восстанавливается из данных.

CREATE TABLE IF NOT EXISTS sys_data_profile (
    -- Имя таблицы — естественный ключ: профиль есть у таблицы, а не у сущности.
    table_name      TEXT PRIMARY KEY,
    entity_index    TEXT NOT NULL,
    row_count       INTEGER NOT NULL DEFAULT 0,
    -- Колонка, по которой считался период (NULL — у таблицы нет даты).
    date_column     TEXT,
    date_min        TEXT,
    date_max        TEXT,
    -- {"connection_mp_ref": 12.5, ...} — доля NULL по ссылочным колонкам, %.
    null_stats_json TEXT NOT NULL DEFAULT '{}',
    -- Сколько заняло измерение: сигнал, что таблица выросла до неудобной.
    computed_ms     INTEGER NOT NULL DEFAULT 0,
    computed_at     TEXT NOT NULL
);
